"""N09 -- finite quotient / orbit / hull candidate searcher (EXPERIMENTAL).

What this is: exact enumeration over explicitly declared finite rings, to produce *candidates and
counterexample leads* for the common-container and saturation questions of M-iii / the hull bridge.
What this is not: a proof certificate, a Lean input, or a statement about IUT. Everything here is
`EXPERIMENTAL` and holds only for the finite model named in the run header.

Model. R = Z/(p^k), or a product of such rings. Submodules (ideals) are enumerated exactly. Units act on
R by multiplication; the orbit of an element is computed, not assumed. The "common container" of two
submodules inside the ambient module is the least submodule containing both, which for a principal ideal
ring is generated by a gcd -- but it is computed by closure, so the arithmetic shortcut is never assumed.

The regression the catalog asks for: restricting the scalars to the prime field F_p (i.e. testing only
"field scalars") gives the wrong answer already at k = 2, because multiplication by p lands in a proper
sublattice. The demo reports that case explicitly.

Bounded: every enumeration has a size cap; exceeding it returns UNKNOWN instead of degrading silently.

Usage:
    py -3 search.py --demo                    # fixed small instances, writes candidate.json
    py -3 search.py --demo --json-out x.json
"""
import argparse
import json
import pathlib
import sys
from itertools import product

CAP_ELEMENTS = 4000          # never enumerate a ring bigger than this many elements
CAP_SUBMODULES = 20000       # never enumerate more submodules than this


class Unknown(Exception):
    pass


def residue_ring(p, k):
    """Return (elements, add, mul, zero, one) for Z/(p^k) as integers 0..p^k-1."""
    n = p ** k
    if n > CAP_ELEMENTS:
        raise Unknown(f'ring Z/({p}^{k}) has {n} elements > cap {CAP_ELEMENTS}')
    els = list(range(n))
    return {'p': p, 'k': k, 'n': n, 'els': els,
            'add': lambda a, b: (a + b) % n,
            'mul': lambda a, b: (a * b) % n,
            'zero': 0, 'one': 1 % n}


def submodules(R):
    """All additive subgroups closed under multiplication by ring elements (i.e. ideals)."""
    n, els = R['n'], R['els']
    out = []
    for d in divide_generators(n):
        sub = sorted({(d * t) % n for t in range(n // d)}) if d else [0]
        out.append(sub)
        if len(out) > CAP_SUBMODULES:
            raise Unknown(f'more than {CAP_SUBMODULES} submodules')
    return sorted(out, key=lambda s: (len(s), s))


def divide_generators(n):
    return [d for d in range(1, n + 1) if n % d == 0]


def closure_under(R, generators):
    """Smallest submodule containing the generators, by closure (no gcd assumption).

    Written against R['add'] / R['mul'] only, so the same code runs for a residue ring and for any
    product of them (where elements are tuples).
    """
    add, mul, zero = R['add'], R['mul'], R['zero']
    is_product = R.get('product', False)
    frontier = [g if is_product else g % R['n'] for g in generators]
    seen = {zero}
    while frontier:
        x = frontier.pop()
        if x in seen:
            continue
        seen.add(x)
        for y in list(seen):
            for z in (add(x, y), add(x, tuple(-v for v in y) if is_product else (-y) % R['n'])):
                if z not in seen:
                    frontier.append(z)
        for a in R['els']:
            z = mul(a, x)
            if z not in seen:
                frontier.append(z)
        if len(seen) > CAP_ELEMENTS:
            raise Unknown('closure exceeded the element cap')
    return sorted(seen, key=lambda t: t if is_product else (t,))


def common_container(R, A, B):
    return closure_under(R, list(A) + list(B))


def unit_orbit(R, x):
    n = R['n']
    units = [a for a in R['els'] if gcd(a, n) == 1]
    return sorted({(a * x) % n for a in units})


def gcd(a, b):
    while b:
        a, b = b, a % b
    return a


def field_scalar_orbit(R, x):
    """The regression: orbit under the prime-field scalars only (multiples of 1 in F_p inside R)."""
    n, p = R['n'], R['p']
    scalars = [a % n for a in range(p)]
    return sorted({(a * x) % n for a in scalars})


def saturation(R, sub):
    """p-saturation: add every y with p*y in the submodule."""
    n, p = R['n'], R['p']
    extra = [y for y in R['els'] if (p * y) % n in sub]
    return sorted(set(sub) | set(extra))


def product_ring(factors):
    """Componentwise product of residue rings; elements are tuples."""
    n = 1
    for f in factors:
        n *= f['n']
    if n > CAP_ELEMENTS:
        raise Unknown(f'product ring has {n} elements > cap {CAP_ELEMENTS}')
    els = list(product(*[f['els'] for f in factors]))
    return {'factors': factors, 'n': n, 'els': els,
            'add': lambda a, b: tuple(x['add'](u, v) for x, u, v in zip(factors, a, b)),
            'mul': lambda a, b: tuple(x['mul'](u, v) for x, u, v in zip(factors, a, b)),
            'zero': tuple(f['zero'] for f in factors),
            'one': tuple(f['one'] for f in factors),
            'product': True,
            'p': factors[0]['p'], 'k': sum(f['k'] for f in factors)}


def product_submodules(R):
    """Ideals of a product of principal ideal rings are products of ideals."""
    out = [()]
    for f in R['factors']:
        out = [a + (b,) for a in out for b in submodules(f)]
    seen, uniq = set(), []
    for combo in out:
        key = tuple(tuple(x) for x in combo)
        if key not in seen:
            seen.add(key)
            uniq.append(key)
    return uniq


def demo():
    runs = []
    for (p, k) in [(3, 2), (3, 1), (5, 1)]:
        R = residue_ring(p, k)
        subs = submodules(R)
        # positive case: two proper submodules share a container strictly bigger than both
        pos = None
        for A, B in product(subs, repeat=2):
            if A is B or A == B:
                continue
            C = common_container(R, A, B)
            if len(C) > max(len(A), len(B)) and len(C) < R['n']:
                pos = {'A': A, 'B': B, 'container': C}
                break
        # rejection case: a pair whose common container is everything (no proper hull)
        rej = None
        for A, B in product(subs, repeat=2):
            C = common_container(R, A, B)
            if len(C) == R['n'] and len(A) < R['n'] and len(B) < R['n']:
                rej = {'A': A, 'B': B, 'container_is_whole_ring': True}
                break
        # regression: field scalars see a smaller orbit than the full unit group
        reg = None
        for x in R['els']:
            full = unit_orbit(R, x)
            partial = field_scalar_orbit(R, x)
            if len(partial) < len(full):
                reg = {'x': x, 'orbit_under_units': full, 'orbit_under_Fp_scalars': partial,
                       'verdict': 'testing only F_p scalars would report a strictly smaller orbit'}
                break
        sat = {'submodule': subs[1] if len(subs) > 1 else [0],
               'saturation': saturation(R, subs[1] if len(subs) > 1 else [0])}
        runs.append({
            'ring': f'Z/({p}^{k}) = Z/{R["n"]}Z',
            'p': p, 'k': k, 'elements': R['n'],
            'submodules': [s for s in subs],
            'submodule_count': len(subs),
            'positive_case': pos,
            'rejection_case': rej,
            'field_scalar_regression': reg,
            'saturation_example': sat,
            'note': ('a principal ideal ring has linearly ordered ideals, so the common container of two '
                     'ideals is one of them: a strictly larger proper container is impossible here, and that '
                     'is why the multi-factor model below is the one that carries the content'),
        })

    # the multi-factor model: Z/9 x Z/9, where a strictly larger proper common container exists
    R2 = product_ring([residue_ring(3, 2), residue_ring(3, 2)])
    A = [(x, 0) for x in (0, 3, 6)]                 # Z/3 x {0}
    B = [(0, x) for x in (0, 3, 6)]                 # {0} x Z/3
    C = sorted(closure_under(R2, A + B))
    runs.append({
        'ring': 'Z/(3^2) x Z/(3^2) = Z/9 x Z/9',
        'p': 3, 'k': 4, 'elements': R2['n'],
        'submodules': [list(map(list, s)) for s in product_submodules(R2)],
        'submodule_count': len(product_submodules(R2)),
        'positive_case': {'A': [list(x) for x in A], 'B': [list(x) for x in B],
                          'container': [list(x) for x in C],
                          'strictly_larger_than_both': len(C) > max(len(A), len(B)),
                          'proper': len(C) < R2['n']},
        'rejection_case': {'A': [list((x, 0)) for x in range(9)],
                           'B': [list((0, y)) for y in range(9)],
                           'container_is_whole_ring': True},
        'field_scalar_regression': None,
        'saturation_example': None,
        'note': ('here a strictly larger proper common container exists (3x3 inside 9x9), which the '
                 'one-factor models cannot exhibit'),
    })

    # a bounded instance that must return UNKNOWN rather than silently shrink
    unknown = None
    try:
        residue_ring(3, 9)
    except Unknown as exc:
        unknown = str(exc)
    return {'tool': 'n09-finite-search', 'tag': 'EXPERIMENTAL', 'runs': runs,
            'unknown_demo': {'input': 'Z/(3^9)', 'outcome': 'UNKNOWN', 'reason': unknown},
            'limits': {'cap_elements': CAP_ELEMENTS, 'cap_submodules': CAP_SUBMODULES},
            'not_a_certificate': True}


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('--demo', action='store_true')
    ap.add_argument('--json-out', default=str(pathlib.Path(__file__).resolve().parent / 'candidate.json'))
    args = ap.parse_args(argv)
    if not args.demo:
        ap.error('nothing to do: pass --demo')
    try:
        out = demo()
    except Unknown as exc:
        sys.stdout.write(json.dumps({'outcome': 'UNKNOWN', 'reason': str(exc)}, ensure_ascii=False) + '\n')
        return 0
    pathlib.Path(args.json_out).write_text(json.dumps(out, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    sys.stdout.write(json.dumps({r['ring']: {'submodules': r['submodule_count'],
                                            'positive': bool(r['positive_case']),
                                            'regression': bool(r['field_scalar_regression'])}
                                 for r in out['runs']}, ensure_ascii=False, indent=2) + '\n')
    return 0


if __name__ == '__main__':
    sys.exit(main())
